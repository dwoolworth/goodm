package goodm

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"text/template"

	"github.com/dwoolworth/goodm/internal"
)

// GenerateOptions controls code generation output.
type GenerateOptions struct {
	PackageName string // Go package name (default "models")
	OutputDir   string // where to write files
	EmbedModel  bool   // embed goodm.Model (default true)
}

// modelTemplateData is the data passed to the code generation template.
type modelTemplateData struct {
	Package        string
	StructName     string
	CollectionName string
	EmbedModel     bool
	Fields         []templateField
	IndexEntries   []string
	NeedsTime      bool
	NeedsBSON      bool
	NeedsGoodm     bool
}

type templateField struct {
	GoName   string
	GoType   string
	BSONName string
	GoodmTag string
}

func joinFields(fields []string) string {
	quoted := make([]string, len(fields))
	for i, f := range fields {
		quoted[i] = `"` + f + `"`
	}
	return strings.Join(quoted, ", ")
}

// renderIndexEntry renders one element of the generated Indexes() slice.
// Plain indexes use the constructors; indexes with options use a struct
// literal, and options discover cannot read back (partial filters,
// collations) are called out in a comment for the developer to fill in.
func renderIndexEntry(idx DiscoveredIndex) string {
	var b strings.Builder
	if idx.HasPartialFilter || idx.HasCollation {
		var missing []string
		if idx.HasPartialFilter {
			missing = append(missing, "a partial filter")
		}
		if idx.HasCollation {
			missing = append(missing, "a collation")
		}
		fmt.Fprintf(&b, "// TODO: index %q has %s that discover cannot reproduce; set PartialFilter/Collation here.\n", idx.Name, strings.Join(missing, " and "))
	}
	customName := idx.Name != "" && idx.Name != idx.DerivedName()
	simple := !idx.Sparse && idx.ExpireAfterSeconds == nil && !idx.HasPartialFilter && !idx.HasCollation && !customName
	switch {
	case simple && idx.Unique:
		fmt.Fprintf(&b, "goodm.NewUniqueCompoundIndex(%s),", joinFields(idx.Keys))
	case simple:
		fmt.Fprintf(&b, "goodm.NewCompoundIndex(%s),", joinFields(idx.Keys))
	default:
		fmt.Fprintf(&b, "{Fields: []string{%s}", joinFields(idx.Keys))
		if idx.Unique {
			b.WriteString(", Unique: true")
		}
		if idx.Sparse {
			b.WriteString(", Sparse: true")
		}
		if customName {
			fmt.Fprintf(&b, ", Name: %q", idx.Name)
		}
		if idx.ExpireAfterSeconds != nil {
			fmt.Fprintf(&b, ", ExpireAfterSeconds: goodm.TTL(%d * time.Second)", *idx.ExpireAfterSeconds)
		}
		b.WriteString("},")
	}
	return b.String()
}

var modelTmpl = template.Must(template.New("model").Funcs(template.FuncMap{
	"joinFields": joinFields,
}).Parse(`package {{ .Package }}

import (
	"log"
{{- if .NeedsTime }}
	"time"
{{- end }}
{{- if .NeedsBSON }}
	"go.mongodb.org/mongo-driver/v2/bson"
{{- end }}
{{- if .NeedsGoodm }}
	"github.com/dwoolworth/goodm"
{{- end }}
)

// {{ .StructName }} was generated by goodm discover from the "{{ .CollectionName }}" collection.
type {{ .StructName }} struct {
{{- if .EmbedModel }}
	goodm.Model ` + "`" + `bson:",inline"` + "`" + `
{{- end }}
{{- range .Fields }}
	{{ .GoName }}	{{ .GoType }}	` + "`" + `bson:"{{ .BSONName }}"{{ if .GoodmTag }} goodm:"{{ .GoodmTag }}"{{ end }}` + "`" + `
{{- end }}
}
{{ if .IndexEntries }}
// Indexes returns the indexes of the {{ .StructName }} model that field tags cannot express.
func (m *{{ .StructName }}) Indexes() []goodm.CompoundIndex {
	return []goodm.CompoundIndex{
{{- range .IndexEntries }}
		{{ . }}
{{- end }}
	}
}
{{ end }}
func init() {
	if err := goodm.Register(&{{ .StructName }}{}, "{{ .CollectionName }}"); err != nil {
		log.Fatalf("goodm: failed to register {{ .StructName }}: %v", err)
	}
}
`))

// GenerateModel generates Go source code for a discovered collection.
func GenerateModel(coll DiscoveredCollection, opts GenerateOptions) ([]byte, error) {
	if opts.PackageName == "" {
		opts.PackageName = "models"
	}

	structName := internal.SanitizeStructName(coll.Name)

	// Skip _id field if embedding Model (it provides _id)
	var fields []templateField
	needsTime := false
	needsBSON := false

	// Indexes are rendered from a copy: a field the embedded Model provides is
	// not emitted, so an index Discover tagged onto it must go to Indexes().
	indexes := append([]DiscoveredIndex(nil), coll.Indexes...)
	for _, f := range coll.Fields {
		if opts.EmbedModel && (f.BSONName == "_id" || f.BSONName == "created_at" || f.BSONName == "updated_at" || f.BSONName == "__v") {
			for i := range indexes {
				if indexes[i].Tagged && len(indexes[i].Keys) == 1 {
					if field, _ := parseIndexField(indexes[i].Keys[0]); field == f.BSONName {
						indexes[i].Tagged = false
					}
				}
			}
			continue
		}

		goName := internal.ToExportedName(f.BSONName)
		goodmTag := internal.FormatGoodmTag(f.IsUnique, f.IsIndexed, f.IndexKind, f.Sparse, f.TTL, f.IsRequired)

		if strings.Contains(f.GoType, "time.Time") {
			needsTime = true
		}
		if strings.Contains(f.GoType, "bson.") {
			needsBSON = true
		}

		fields = append(fields, templateField{
			GoName:   goName,
			GoType:   f.GoType,
			BSONName: f.BSONName,
			GoodmTag: goodmTag,
		})
	}

	// Every index Discover did not express as a field tag: compound indexes,
	// single-key indexes with options or a custom name, second indexes on a
	// field, and single-key indexes on paths that are not generated fields.
	var indexEntries []string
	for _, idx := range indexes {
		if idx.Name == "_id_" || idx.Tagged {
			continue
		}
		if idx.ExpireAfterSeconds != nil {
			needsTime = true
		}
		indexEntries = append(indexEntries, renderIndexEntry(idx))
	}

	data := modelTemplateData{
		Package:        opts.PackageName,
		StructName:     structName,
		CollectionName: coll.Name,
		EmbedModel:     opts.EmbedModel,
		Fields:         fields,
		IndexEntries:   indexEntries,
		NeedsTime:      needsTime,
		NeedsBSON:      needsBSON,
		NeedsGoodm:     true, // init() always calls goodm.Register
	}

	var buf bytes.Buffer
	if err := modelTmpl.Execute(&buf, data); err != nil {
		return nil, err
	}

	// Format with gofmt
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		// Return unformatted if formatting fails (helpful for debugging)
		return buf.Bytes(), nil
	}

	return formatted, nil
}
